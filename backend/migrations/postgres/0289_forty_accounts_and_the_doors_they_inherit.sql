DO $$
DECLARE
    fresh    INTEGER;
    families INTEGER;
    doors    INTEGER;
    orphan   TEXT;
BEGIN
    SELECT count(*) INTO fresh FROM ledger_account WHERE length(account_code) = 4 AND NOT is_group;
    IF fresh <> 40 THEN RAISE EXCEPTION 'expected 40 new accounts, got %', fresh; END IF;

    -- Every family an account declares has to be a family that exists, or the
    -- account declares a question nothing can answer and every posting to it
    -- fails at the trigger 0288 installed.
    SELECT a.account_code INTO orphan
      FROM ledger_account a
     WHERE a.category_family IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM line_category c WHERE c.family = a.category_family)
     LIMIT 1;
    IF orphan IS NOT NULL THEN
        RAISE EXCEPTION 'account % declares a category family with no values', orphan;
    END IF;

    SELECT count(*) INTO families
      FROM ledger_account WHERE length(account_code) = 4 AND category_family IS NOT NULL;
    IF families <> 24 THEN RAISE EXCEPTION 'expected 24 accounts to take a category, got %', families; END IF;

    SELECT count(*) INTO doors FROM account_category_policy;
    IF doors <> 12 THEN RAISE EXCEPTION 'expected 12 kept doors, got %', doors; END IF;

    -- A kept door must be stricter than the account it sits on, or it is noise.
    IF EXISTS (
        SELECT 1 FROM account_category_policy p
          JOIN ledger_account a USING (account_code)
         WHERE (p.posting_mode, p.manual_je_policy) = (a.posting_mode, a.manual_je_policy)
    ) THEN
        RAISE EXCEPTION 'a category policy repeats its account''s policy; drop the row instead';
    END IF;
END $$;
