-- Forty accounts, and the doors they inherit.
--
-- The chart the client gave us has 6,908 posting accounts. 0243/0244 pulled the
-- unit axis out and left 190. This migration pulls the rest of the identity out
-- and leaves **40** — one per line of a balance sheet or a profit and loss, and
-- not one more. Everything the other 150 distinguished still exists; it moved
-- to `line_category` (0287), to `asset_class` (0287), or to a column the line
-- already carried: `bank_account_id`, `asset_id`, `supplier_id`,
-- `counter_site_id`, and the tax, facility and principal registers.
--
-- The whole argument, the 190 → 40 map and the comparison against an outside
-- 30-account proposal are in `docs/coa-thirty.md`. The shape is frozen in
-- `docs/coa-40-contract.md`. This file is the shape becoming true.
--
-- # The codes
--
-- Four digits, hanging off the single-digit roots the client's own chart
-- already has (`1` ASSET … `8` BEBAN NON OPERASIONAL). No new heading rows:
-- `root_class` is still the first digit, `financial_statements.rs` still groups
-- by it, and the prefix-tree rollup still works because `1101 LIKE '1%'`.
--
-- Four digits and not ten, deliberately: a four-digit code cannot be mistaken
-- for one of the client's, in a spreadsheet or in a conversation. All forty
-- carry `code_provenance = 'PENDING_CLIENT_CODE'` — the codes are ours, the
-- names are theirs, and `docs/finance-legacy-codes.md` says how an accountant
-- gets their own numbers back.
--
-- # The doors, which are the part worth reading twice
--
-- Every one of the 190 carries a posting policy somebody decided (0261–0268):
-- `posting_mode` says whether a rule, a person, or nobody may post, and
-- `manual_je_policy` says whether a person may journal it freely, only through
-- an approved correction, or not at all. Merging 190 accounts into 40 merges
-- 190 policies into 40, and there are two obvious ways to do that and both are
-- wrong.
--
-- Take the STRICTEST source and you close doors that are open today: cash on
-- hand, petty cash and deposits-in-transit all allow an approved correction,
-- but `Modal Kasir` does not, so a single merged `1101 Kas` would refuse the
-- cash-variance correction that the till reconciliation depends on.
--
-- Take the MOST PERMISSIVE and you open doors that are shut today: `Selisih
-- Pembulatan` is posted only by a rule, and it would land inside a `4301` that
-- a person may journal, because `Pendapatan Sewa Gedung` may be journalled.
--
-- So the policy splits the way the identity split. The ACCOUNT takes the most
-- permissive of its sources, so the account blocks nothing that used to be
-- allowed; and `account_category_policy` carries the source's own policy
-- wherever that was stricter, at the category grain the detail moved to. Twelve
-- rows, each naming the client account it was kept from. A line is governed by its
-- category's row when there is one and by its account otherwise.
--
-- Sixteen accounts declare no category family at all — bank, the asset
-- accounts, payables, loans, equity — because their detail is a sub-ledger row
-- and the sub-ledger's own document governs it. Four of those have sources that
-- disagree: contract-in-progress among the fixed assets, pre-opening among the
-- intangibles, the owner's payable among the loans, and the operating-equipment
-- replacement charge among the depreciation. All four resolve to
-- SEMI_AUTO/OVERRIDE, which says: a person may reach it through a correction
-- somebody approved, and may not journal it freely. That is the policy those
-- four already had; what changes is that their neighbours now share it.
--
-- Generated by `outputs/coa_thirty/gen-accounts.py` against the head chart, so
-- the merge is reproducible and nobody typed a policy by hand.

-- # The counterparty list, restated
--
-- `ledger_account_counterparty_is_rare` names the seven client codes that may
-- carry `requires_counter_site`, so that the flag cannot spread by accident to
-- accounts where "the unit on the other side" has no meaning. The list is right
-- and it is also a list of codes that are about to stop being the codes. Two
-- accounts inherit the flag: `1302` goods in transit, where the counterparty is
-- where the goods came from, and `1501` the inter-unit current account, where
-- it is who the balance is with.
--
-- Restated in full rather than appended to, for the reason 0257 had to learn:
-- a DROP-and-ADD constraint that two lanes both touch loses whichever half
-- merged second, silently.

ALTER TABLE ledger_account DROP CONSTRAINT IF EXISTS ledger_account_counterparty_is_rare;
ALTER TABLE ledger_account ADD CONSTRAINT ledger_account_counterparty_is_rare
    CHECK (requires_counter_site = FALSE OR account_code IN (
        -- the two that carry it from here on
        '1302', '1501',
        -- the client codes 0290 retires, kept legal until they are inactive
        '1011203001', '1011204001', '1021401001', '1021402001', '1021403001',
        '2012301001', '2012302001'
    ));

CREATE TABLE account_category_policy (
    account_code     TEXT NOT NULL REFERENCES ledger_account (account_code),
    category_code    TEXT NOT NULL REFERENCES line_category (category_code),
    posting_mode     TEXT NOT NULL
        CHECK (posting_mode IN ('AUTO_ONLY', 'SEMI_AUTO', 'MANUAL', 'BLOCKED')),
    manual_je_policy TEXT NOT NULL
        CHECK (manual_je_policy IN ('NO', 'OVERRIDE', 'YES')),
    note             TEXT,
    PRIMARY KEY (account_code, category_code)
);

COMMENT ON TABLE account_category_policy IS
    'Overrides ledger_account.posting_mode / manual_je_policy for one category '
    'on one account. Present only where a client account that folded into a '
    'shared account had a stricter door than the shared account has; absent '
    'means the account''s own policy governs.';

