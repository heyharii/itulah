//! The 200 acceptance scenarios, exactly as the locked plan states them.
//!
//! Transcribed mechanically from `docs/commercial-v1-acceptance-test-plan.md`
//! §6 rather than by hand. That matters more than it looks: the point of this
//! table is to be compared down its left-hand column against the plan, and a
//! row that drifted from the document during copying would make the comparison
//! lie in the one direction nobody checks — a scenario that reads plausible
//! and is not the one the owner locked.
//!
//! The `scenario` and `must_prove` columns are the plan's own wording, kept in
//! Indonesian. Translating them here would fork the contract into two
//! languages and leave no way to tell which one an implementer read.
//!
//! Nothing in this file runs. It declares WHAT has to be proven; `checks`
//! says which of them this harness can prove today, and the runner joins the
//! two so that an unproven row is visible rather than absent.

/// One row of the plan's matrix.
pub struct Row {
    pub id: &'static str,
    /// P0 — must pass to release the capability. P1 — also tested before the
    /// scope is called ready.
    pub priority: &'static str,
    /// UNIT, INT, PROP, RACE, FAULT, E2E, PERF. This is what decides whether a
    /// row is reachable from a test with no database and no provider, so the
    /// runner reads it when it has to explain why a row is not encoded.
    pub level: &'static str,
    /// The decision the row hangs off, as the plan's own "Aturan" column gives
    /// it. `—` is the plan's mark for "the common contract already stated",
    /// not an absence of rule, and is reported under that name rather than
    /// silently folded into some decision it might belong to.
    pub decision: &'static str,
    pub scenario: &'static str,
    pub must_prove: &'static str,
}

/// What each three-letter prefix covers, for the report's section headings.
pub fn group_name(prefix: &str) -> &'static str {
    match prefix {
        "CFG" => "Configuration, versions and validation",
        "PRC" => "Regular price and markdown",
        "ELG" => "Scope, qualification and usage limits",
        "MON" => "Monetary benefit and discount allocation",
        "COM" => "Best Price, Exclusive and Combine",
        "BXY" => "Buy X Get Y and unit quantity",
        "PTS" => "Earning and promotion points",
        "LRD" => "Points redeemed into a voucher",
        "CPN" => "Coupon and scarce usage",
        "VCH" => "Voucher, ledger balance and authorisation",
        "TAX" => "Tax, charges and the definition of value",
        "PAY" => "Checkout and payment state machine",
        "RET" => "Returns, unit identity and reversal",
        "RFD" => "Refund allocation, attempts and remaining obligation",
        "OFF" => "Offline, sync and Cloud/Store parity",
        "CAM" => "Campaign measurement and promotion analytics",
        "DAT" => "Persistence, immutability and audit",
        "SEC" => "Access and command boundaries",
        "PRP" => "Property tests and reference calculation",
        "E2E" => "Whole business journeys",
        "OPS" => "Performance and operational recovery",
        _ => "unknown group",
    }
}

