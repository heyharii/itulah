import {
  Activity,
  Printer,
  RefreshCw,
  ScrollText,
  Server,
  Settings2,
  UserCog,
  UserRound,
} from "lucide-react"

import type { AppModule } from "@/lib/navigation"

/// This module's row in the sidebar and the sub-items under it.
/// Owned by the module, composed by `lib/navigation.ts` — so adding a screen
/// here never touches another module's file.
///
/// # Tidied 2026-09-27
///
/// Six rows, not eleven. "Nodes" confused people who read it as the org chart
/// rather than the machines — so the whole cluster of screens ABOUT a store's
/// server (the register, whether it is up, its incidents, its sync lane) is
/// one row, "Store servers", with those as tabs rather than five rows that
/// each said "node" or "origin" somewhere on the page. Those two words are
/// gone from this module's copy; a shop's own machine is a "store server" (or
/// a "warehouse server" for the warehouse) everywhere a person reads it.
///
/// Access is gone as a screen of its own. Its two halves went to where they
/// actually belonged: who may sign in at the CENTRE — job role, unit, suspend,
/// reset — merged into Account, which is now "Users & roles" and holds the
/// role list too; and the RFID reader registry, which is a device like a till
/// or a printer, moved to Devices. What Access used to let an admin type by
/// hand — a person's role AT A NODE — is now derived from their job role and
/// unit, which is why there is no "grant access" form left to point at.
///
/// Your OWN account — the password box, "change my password" — is not here
/// any more either: it moved to the avatar menu as "My account", because it
/// is not a department of the business and never was.
export const systemNav: AppModule = {
  id: "system",
  label: "System",
  icon: Settings2,
  // Not the first row below, on purpose: bare `/system` has meant the store
  // register since before this module had a name for it, and `base` !==
  // `home` is exactly what `AppModule.base`'s own doc says that buys — a
  // redirect from the bare prefix generated by `routes.tsx`, landing where the
  // word has always pointed rather than on whichever row happens to be first.
  home: "/system/servers",
  base: "/system",
  // Not drawn in the sidebar. The screens stay routed and stay in ⌘K — the
  // module is simply not one of the places the sidebar offers.
  hidden: true,
  sections: [
    {
      items: [
        {
          // Everyone who can sign in at the centre, their job role, and the
          // role list itself as a tab. See `screens/system/users.tsx`.
          path: "/system/users",
          label: "Users",
          icon: UserRound,
          moved: ["/system/access", "/system/account"],
        },
        // The organisation — head office and the stores, their premises and
        // who is in charge of each (0600-0602) — left on 2026-10-04 for the
        // Master menu, where a register of the company belongs; the screen
        // answers at `/master/organisation`, the old path redirects (see
        // `moved` on the item there). Its console half stays: whether a
        // store's server is up is Store servers, beside it.
        {
          // The register, whether each is up, its incidents and its sync
          // lane — one page, four tabs. See `screens/system/servers.tsx`.
          path: "/system/servers",
          label: "Store Servers",
          icon: Server,
          // Not `/system` — that redirect is `AppModule.base`'s, generated
          // automatically because `home` already points here. Listing it
          // again here would register the same route twice and refuse to
          // start; see the note on `home` above.
          moved: [
            "/system/monitoring",
            "/system/health",
            "/system/incidents",
            "/system/sync",
          ],
        },
        {
          // Every till, printer and reader enrolled to a store server, and
          // now the RFID reader registry too — a reader is a device like the
          // rest of them.
          path: "/system/devices",
          label: "Devices",
          icon: Printer,
        },
        {
          path: "/system/notifications",
          label: "Notifications",
          icon: Activity,
        },
        { path: "/system/activity", label: "Activity", icon: ScrollText },
        /// The warehouse server's own sync and sign-in. The screens live in
        /// `screens/operations/node/` and keep their old paths.
        { path: "/operations/node", label: "Sync", icon: RefreshCw },
        { path: "/operations/node/account", label: "Account", icon: UserCog },
      ],
    },
  ],
}
