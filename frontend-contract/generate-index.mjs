// Rewrite src/index.ts from whatever is currently in src/contract/.
//
// The barrel used to be hand-maintained, which made it a second list that had
// to agree with the first: export a new type from Rust, forget this file, and
// the type is simply invisible to the browser with nothing failing anywhere.
// Generating it removes the chance to forget.

import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const generated = join(here, "src", "contract");

const names = readdirSync(generated)
  .filter((file) => file.endsWith(".ts") && file !== "index.ts")
  .map((file) => file.slice(0, -3))
  .sort((a, b) => a.localeCompare(b, "en"));

const header = `// This file is generated by generate-index.mjs. Do not edit it manually.
//
// The wire, as the server declares it. Every type below is generated from the
// Rust struct the server actually serialises — see
// backend/tests/contract_types.rs. Regenerate the lot with \`make contract\`.
`;

const body = names
  .map((name) => `export type { ${name} } from "./contract/${name}";`)
  .join("\n");

writeFileSync(join(here, "src", "index.ts"), `${header}\n${body}\n`);
console.log(`contract barrel: ${names.length} types`);
