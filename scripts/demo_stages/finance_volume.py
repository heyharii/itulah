def run_pool(label, items, worker, workers=WORKERS):
    """Run `worker(item)` over `items` on a small thread pool; independent
    documents only — nothing here depends on another item in the same call
    finishing first. Errors are collected and reported, not allowed to stop
    the batch: one bad line item beats losing the other 349."""
    if not items:
        return 0, []
    done, errors = 0, []
    with ThreadPoolExecutor(max_workers=workers) as pool:
        futures = {pool.submit(worker, item): item for item in items}
        for future in as_completed(futures):
            try:
                if future.result():
                    done += 1
            except (SystemExit, Exception) as error:  # noqa: BLE001 — Node.call raises SystemExit on HTTP errors
                errors.append(f"{items_label(futures[future])}: {error}")
    if errors:
        say(f"!! {label}: {len(errors)} refused —")
        for e in errors[:10]:
            say(f"     {e}")
        if len(errors) > 10:
            say(f"     … and {len(errors) - 10} more")
    return done, errors


def items_label(item):
    if isinstance(item, dict):
        return item.get("number") or item.get("memo") or item.get("reference") or str(item)[:60]
    return str(item)[:60]


