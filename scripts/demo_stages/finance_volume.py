def build_payment_plan(rng, bills_by_number):
    """Which of the plan's bills get paid, by what method, how much (some
    only in part), and — for GIRO — what column of the Giro Board it should
    end at."""
    plan = []
    giro_states = ["ISSUED", "DELIVERED", "DUE", "CLEARED", "REJECTED"]
    candidates = [b for b in bills_by_number.values()
                  if b.get("kind") == "EXPENSE" and b.get("status") in ("POSTED", "PARTIALLY_PAID")
                  and not b["invoice_number"].startswith("ADV-BILL-")]  # reserved for supplier_advances to apply against
    rng.shuffle(candidates)
    giro_i = 0
    for i, bill in enumerate(candidates):
        if i % 3 == 0:  # ~1/3 left entirely unpaid (feeds ageing/overdue)
            continue
        outstanding = bill.get("outstanding_minor") or bill.get("total_minor")
        if not outstanding:
            continue
        partial = (i % 7 == 0)  # ~14% paid only in part
        amount = outstanding if not partial else max(1000, (outstanding * rng.randint(40, 85)) // 100)
        roll = i % 8
        if roll <= 3:
            method, giro_state = "TRANSFER", None
        elif roll == 4:
            method, giro_state = "CASH", None
        else:
            method, giro_state = "GIRO", giro_states[giro_i % len(giro_states)]
            giro_i += 1
        month = int(bill["invoice_date"][5:7])
        day = clamp_day(rng.randint(1, 27), month)
        pay_day = max(day, int(bill["invoice_date"][8:10]))
        plan.append({
            "reference": f"PAY-{bill['invoice_number']}", "invoice_id": bill["invoice_id"],
            "invoice_number": bill["invoice_number"], "amount": amount,
            "date": ymd(YEAR, month, clamp_day(pay_day, month)),
            "method": method, "giro_state": giro_state,
            "giro_number": f"BCA-GRV-{i:04d}" if method == "GIRO" else None,
            "giro_due_date": (date(YEAR, month, clamp_day(pay_day, month)) + timedelta(days=25)).isoformat()
                              if method == "GIRO" else None,
        })
    return plan


def payment_worker(cloud, have, item):
    existing = have.get(item["reference"])
    if existing is not None:
        payment = existing
    else:
        # Re-check the bill's live outstanding right before posting: the plan
        # was built off a snapshot, and a rig that already has other activity
        # on the same bill (a voucher SETTLE, a hand-keyed payment) can have
        # moved it since. Skip rather than over-pay.
        live = cloud.get(f"/api/v1/finance/bills/{item['invoice_id']}")
        outstanding = live.get("outstanding_minor") or 0
        if outstanding <= 0:
            return False
        amount = min(item["amount"], outstanding)
        account_key = {"TRANSFER": BANK_KEY, "GIRO": BANK_KEY, "CASH": "cash"}[item["method"]]
        account_q = BANK_Q if item["method"] != "CASH" else ""
        payment = cloud.post("/api/v1/finance/payments", {
            "unit_id": HO_UNIT, "payment_date": item["date"], "method": item["method"],
            "account_key": account_key, "account_qualifier": account_q, "total_minor": amount,
            "reference": item["reference"], "note": None,
            "allocations": [{"invoice_id": item["invoice_id"], "amount_minor": amount}],
            "giro_number": item["giro_number"], "giro_due_date": item["giro_due_date"],
        })
    pid = payment.get("payment_id") or payment.get("id")
    if payment.get("status") == "DRAFT":
        payment = cloud.post(f"/api/v1/finance/payments/{pid}/post", {"posting_date": item["date"]})
    if item["giro_state"] and item["giro_state"] != "ISSUED":
        advance_giro(cloud, item["giro_number"], item["giro_state"], item["date"])
    return True


def advance_giro(cloud, number, target_state, base_date):
    """Walk a freshly issued giro through as many states as `target_state`
    needs. Idempotent: re-checks the giro's live status first."""
    order = ["ISSUED", "DELIVERED", "DUE", "CLEARED"]
    giro = None
    for g in rows(cloud.get("/api/v1/finance/giros?limit=500")):
        if g.get("number") == number:
            giro = g
            break
    if giro is None:
        return
    gid = giro["giro_id"]
    status = giro["status"]
    if status in ("CLEARED", "REJECTED"):
        return
    if target_state == "REJECTED":
        if status not in ("CLEARED", "REJECTED"):
            cloud.post(f"/api/v1/finance/giros/{gid}/reject", {
                "on": base_date, "statement_line_id": None,
                "reason": "Ditolak bank: saldo/kliring tidak berhasil"})
        return
    target_idx = order.index(target_state)
    steps = {"DELIVERED": "deliver", "DUE": "due", "CLEARED": "clear"}
    for state in order[1:target_idx + 1]:
        giro_now = next((g for g in rows(cloud.get("/api/v1/finance/giros?limit=500"))
                          if g.get("number") == number), None)
        if giro_now is None or giro_now["status"] == state or order.index(giro_now["status"]) >= order.index(state):
            continue
        if state == "CLEARED":
            cloud.post(f"/api/v1/finance/giros/{gid}/clear",
                       {"on": base_date, "statement_line_id": None, "reason": None})
        else:
            cloud.post(f"/api/v1/finance/giros/{gid}/{steps[state]}", {})


