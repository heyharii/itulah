def run(cloud, dc, store, ctx):
    print("\n\033[1m── demo-populate: finance_volume — ~1000 documents of Finance history "
          "(Jan-Sep 2026)\033[0m", flush=True)
    as_user = ctx.get("as_user")
    finance = as_user("cloud", "rina") if as_user else cloud
    checker = as_user("cloud", "admin") if as_user else cloud
    rng = random.Random(SEED)

    ensure_periods_open(finance)
    ensure_suppliers(finance)
    bank_id = bank_account_id(finance)

    # ---- bills -------------------------------------------------------
    bill_plan = build_bill_plan(rng)
    have_bills = {b["invoice_number"]: b for b in list_all(finance, "/api/v1/finance/bills", "limit=500")}
    done, _ = run_pool("bills", bill_plan, lambda item: bill_worker(finance, have_bills, item))
    say(f"+ bills: {done} created (of {len(bill_plan)} planned), {len(have_bills)} already existed")

    merch_plan = build_draft_merchandise_plan(rng)
    have_merch = {b["invoice_number"] for b in have_bills.values()}
    mdone, merrors = run_pool("draft merchandise bills", merch_plan,
                              lambda item: merch_bill_worker(finance, have_merch, item))
    if merrors and mdone == 0:
        say("!! MERCHANDISE bills without a receipt are refused by this build — skipped entirely")
    else:
        say(f"+ draft merchandise bills: {mdone} created (of {len(merch_plan)} planned)")

    # refresh the bill index (with outstanding_minor) for payments/vouchers/advances
    bills_by_number = {b["invoice_number"]: b for b in list_all(finance, "/api/v1/finance/bills", "limit=500")}

    # ---- payments ------------------------------------------------------
    payment_plan = build_payment_plan(rng, bills_by_number)
    have_payments = {p["reference"]: p for p in list_all(finance, "/api/v1/finance/payments", "limit=200")
                     if p.get("reference")}
    done, _ = run_pool("payments", payment_plan,
                       lambda item: payment_worker(finance, have_payments, item))
    say(f"+ payments: {done} created/advanced (of {len(payment_plan)} planned), "
        f"{len(have_payments)} already existed")

    # refresh bills again: payments changed outstanding_minor
    bills_by_number = {b["invoice_number"]: b for b in list_all(finance, "/api/v1/finance/bills", "limit=500")}

    # ---- vouchers (BKK/BKM) --------------------------------------------
    voucher_plan = build_voucher_plan(rng, bills_by_number)
    have_vouchers = {d.get("memo"): d for d in list_all(finance, "/api/v1/finance/cash-documents", "limit=500")
                     if d.get("status") != "CANCELLED"}
    done, verrors = run_pool("vouchers", voucher_plan,
                             lambda item: voucher_worker(finance, checker, have_vouchers, item))
    say(f"+ vouchers (BKK/BKM): {done} created/advanced (of {len(voucher_plan)} planned), "
        f"{len(have_vouchers)} already existed")

    # ---- manual journal --------------------------------------------------
    journal_plan = build_journal_plan(rng)
    have_journal = {j.get("memo") for j in list_all(
        finance, "/api/v1/finance/journal", f"from={YEAR}-01-01&to={YEAR}-09-30&limit=500")}
    done, _ = run_pool("journal", journal_plan, lambda item: journal_worker(finance, have_journal, item))
    say(f"+ manual journal: {done} created (of {len(journal_plan)} planned), "
        f"{len(have_journal)} already existed")

    # ---- advances, assets and bank statements ---------------------------
    # Each phase below is sequential (a document's own steps depend on one
    # another) and wrapped so a refusal in one does not cost the rest — the
    # same spirit as `demo-populate.py`'s own top-level stage loop.
    for label, step in (
            ("supplier advances", lambda: supplier_advances(finance, checker, bills_by_number, rng)),
            ("employee kasbon", lambda: employee_kasbon(finance, checker, rng)),
            ("fixed assets", lambda: assets(finance, ctx)),
            *[(f"bank statement {YEAR}-{m:02d}", lambda m=m: bank_statement_month(finance, bank_id, m))
              for m in BANKABLE_MONTHS],
    ):
        try:
            step()
        except (SystemExit, Exception) as error:  # noqa: BLE001
            say(f"!! {label} failed: {error}")

    # ---- verification ----------------------------------------------------
    print("\n\033[1m── finance_volume: counts per screen\033[0m", flush=True)
    verify(finance)


def verify(cloud):
    bills = list_all(cloud, "/api/v1/finance/bills", "limit=500")
    by_status = {}
    for b in bills:
        by_status[b["status"]] = by_status.get(b["status"], 0) + 1
    say(f"bills: {len(bills)} total — {by_status}")

    payments = list_all(cloud, "/api/v1/finance/payments", "limit=200")
    by_method = {}
    for p in payments:
        by_method[p.get("method")] = by_method.get(p.get("method"), 0) + 1
    say(f"payments: {len(payments)} total — {by_method}")

    docs = list_all(cloud, "/api/v1/finance/cash-documents", "limit=500")
    by_kind_status = {}
    for d in docs:
        key = (d.get("kind"), d.get("status"))
        by_kind_status[key] = by_kind_status.get(key, 0) + 1
    say(f"cash documents (BKK/BKM): {len(docs)} total — {by_kind_status}")

    journal = list_all(cloud, "/api/v1/finance/journal", f"from={YEAR}-01-01&to={YEAR}-09-30&limit=500")
    say(f"journal entries Jan-Sep: {len(journal)}")

    giros = rows(cloud.get("/api/v1/finance/giros?limit=500"))
    by_giro_status = {}
    for g in giros:
        by_giro_status[g.get("status")] = by_giro_status.get(g.get("status"), 0) + 1
    say(f"giros: {len(giros)} total — {by_giro_status}")

    statements = list_all(cloud, "/api/v1/finance/bank-statements", "limit=500")
    matched = unmatched = 0
    for s in statements:
        sid = s.get("statement_id") or s.get("id")
        for line in rows(cloud.get(f"/api/v1/finance/bank-statements/{sid}/lines")):
            if line.get("matched_journal_line_id") or line.get("status") in ("MATCHED", "BOOKED"):
                matched += 1
            else:
                unmatched += 1
    say(f"bank statements: {len(statements)}, lines matched/booked {matched}, unmatched {unmatched}")

    assets_ = list_all(cloud, "/api/v1/finance/assets", "limit=500")
    say(f"fixed assets: {len(assets_)}")

    sup_advances = rows(cloud.get("/api/v1/finance/supplier-advances"))
    emp_advances = rows(cloud.get("/api/v1/finance/advances"))
    say(f"supplier advances outstanding: {len(sup_advances)}; employee advances: {len(emp_advances)}")

    try:
        tb = cloud.get(f"/api/v1/finance/trial-balance?as_of={YEAR}-09-29")
        total_debit = sum(r.get("debit_minor", 0) for r in rows(tb))
        total_credit = sum(r.get("credit_minor", 0) for r in rows(tb))
        say(f"trial balance as of {YEAR}-09-29: debit Rp {total_debit:,} / credit Rp {total_credit:,} "
            f"({'BALANCED' if total_debit == total_credit else 'OUT OF BALANCE'})")
    except SystemExit as error:
        say(f"!! trial balance check failed: {error}")
