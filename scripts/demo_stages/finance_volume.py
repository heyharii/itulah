def rows(payload):
    if isinstance(payload, list):
        return payload
    if isinstance(payload, dict):
        for key in ("rows", "items", "data", "results"):
            if isinstance(payload.get(key), list):
                return payload[key]
    return []


def say(msg):
    print(f"  {msg}", flush=True)


def ymd(year, month, day):
    return f"{year:04d}-{month:02d}-{day:02d}"


def clamp_day(day, month, year=YEAR):
    last = 28
    if month in (1, 3, 5, 7, 8, 10, 12):
        last = 31
    elif month in (4, 6, 9, 11):
        last = 30
    return max(1, min(day, last))


def rp(rng, lo, hi, step=1000):
    """A round Rupiah figure — nobody bills Rp 3,417,286 for electricity."""
    n = rng.randint(lo // step, hi // step)
    return n * step


def list_all(node, path, query=""):
    """Every row of a cursor-paginated (`rows`/`next_cursor`) or plain-array
    list endpoint. `query` is the query string without a leading `?`."""
    out = []
    cursor = None
    for _ in range(200):
        q = query
        if cursor:
            q = f"{q}&cursor={cursor}" if q else f"cursor={cursor}"
        page = node.get(f"{path}?{q}" if q else path)
        if isinstance(page, dict) and "rows" in page:
            got = page["rows"]
            out.extend(got)
            cursor = page.get("next_cursor")
            if not cursor or not got:
                break
        else:
            out.extend(rows(page))
            break
    return out


