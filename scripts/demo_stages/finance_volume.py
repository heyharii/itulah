def voucher_worker(cloud, checker, have, item):
    existing = have.get(item["memo"])
    if existing is None:
        # Re-check every SETTLE line's live outstanding right before posting
        # (see `payment_worker`'s comment) — a plan built off a snapshot can
        # be stale by the time this document is created.
        lines = []
        for line in item["lines"]:
            if line["kind"] != "SETTLE":
                lines.append(line)
                continue
            live = cloud.get(f"/api/v1/finance/bills/{line['invoice_id']}")
            outstanding = live.get("outstanding_minor") or 0
            if outstanding <= 0:
                continue
            amount = min(line["amount_minor"], outstanding)
            discount = min(line["discount_minor"], amount)
            lines.append({**line, "amount_minor": amount, "discount_minor": discount})
        if not lines:
            return False
        money = CASH_HO if item["method"] == "CASH" else BANK
        doc = cloud.post("/api/v1/finance/cash-documents/voucher", {
            "doc_date": item["date"], "direction": item["direction"], "money": money,
            "method": item["method"], "reference": None, "giro_number": None, "giro_due_date": None,
            "giro_bank": None, "party_type": item["party_type"], "supplier_id": item["supplier_id"],
            "employee_id": None, "party_name": item["party_name"], "memo": item["memo"],
            "lines": lines,
        })
        doc_id = doc.get("document_id") or doc.get("id")
        status = doc.get("status", "DRAFT")
    else:
        doc_id = existing.get("document_id") or existing.get("id")
        status = existing.get("status")
    if item["state"] == "DRAFT":
        return True
    if status == "DRAFT":
        checker.post(f"/api/v1/finance/cash-documents/{doc_id}/approve", {})
        status = "APPROVED"
    if item["state"] == "APPROVED":
        return True
    if status == "APPROVED":
        cloud.post(f"/api/v1/finance/cash-documents/{doc_id}/post", {})
    return True


