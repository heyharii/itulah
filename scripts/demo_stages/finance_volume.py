"""finance_volume — a full trading history's worth of volume on top of `finance`.

Runs after `finance` in demo-populate's ORDER (it needs the account links, the
BCA giro account and 0001/0002 that stage sets up). Where `finance`
plants one example of each document so every screen has *something*, this
stage plants hundreds so every screen looks like a business that has been
open for months: ~25 suppliers, ~350 bills, ~250 payments, ~250 BKK/BKM
vouchers, ~100 manual journals, a monthly bank statement, ~30 supplier
advances, ~30 employee advances (kasbon) and ~30 fixed assets — spread across
January through September 2026.

Every document goes through the same HTTP endpoints the hub's screens call;
nothing here writes SQL. Re-running is safe: each document is looked up by
its own number/reference/memo first and skipped if it is already there, so a
second run only fills in whatever the first one did not reach.

Numbers are generated by `random.Random(2026)`, called in one fixed,
single-threaded pass to build the whole plan *before* any network call, so
the plan — and therefore every invoice number, amount and date — is the same
on every run regardless of how the network calls that execute it interleave.
Independent documents (bills, then payments, then vouchers, then journals)
are then created through a small thread pool, since none of them depends on
another finishing first within its own phase.

  suppliers   ~25: PLN, PDAM, Telkom, landlords, cleaning, security,
              ekspedisi, ATK/percetakan, repairs, consultant — mostly EXPENSE
              category, a handful MERCHANDISE for Buying-screen variety
  bills       ~350 EXPENSE bills (listrik/PDAM/internet per store, sewa
              quarterly, HO cleaning/security/internet/ATK/consultant,
              scattered ekspedisi/repairs), most posted, some left DRAFT,
              some overdue, some paid only in part
  payments    ~250 Payment Entries settling bills: TRANSFER, CASH and GIRO;
              every GIRO payment is walked through the giro lifecycle so the
              Giro Board has issued/delivered/due/cleared/rejected+replaced
  vouchers    ~250 BKK/BKM through POST /finance/cash-documents/voucher: BKK
              settling a bill (+ a bank-fee OTHER line, some with POTONGAN),
              BKM for bank interest, other income, scrap sales, kasbon
              repayment; ~10% left DRAFT/APPROVED for a busy month-end desk
  journal     ~100 manual entries: accruals, reclasses, depreciation-style
              adjustments, spread across the months
  bank        one BCA HO statement per month for Jan-Aug (Sep already has one
              from `finance`), lines mirroring that month's postings plus a
              few bank-only lines, the easy ones booked off the statement
  advances    ~30 supplier advances against PO-DEMO-001/002 (the only POs
              this rig has), some applied to later EXPENSE bills of the same
              supplier; ~30 employee kasbon over the 5 employees the rig has,
              paid and some settled
  assets      ~30 fixed assets (AC per store, computers/furniture at HO,
              display racks at stores, a company car) capitalised and run
              through September's depreciation

Who does what, matching `finance`: rina (Cloud, Finance HO) keys everything;
admin is the second signature on cash documents and advances.
"""

