def supplier_advances(cloud, checker, bills_by_number, rng):
    pos = {p["po_number"]: p for p in rows(cloud.get("/api/v1/purchase-orders?limit=200"))}
    plan = []
    for n in range(30):
        po_number = "PO-DEMO-001" if n % 2 == 0 else "PO-DEMO-002"
        supplier = "0001" if n % 2 == 0 else "0002"
        month = MONTHS[n % len(MONTHS)]
        target_supplier, target_month = ADV_TARGET_BILLS[n] if n < len(ADV_TARGET_BILLS) else (None, None)
        apply_to = (f"ADV-BILL-{target_supplier}-{YEAR}{target_month:02d}-{n:02d}"
                    if target_supplier == supplier else None)
        plan.append({
            "reference": f"UM-VOL-{n:03d}", "po_number": po_number, "supplier": supplier,
            "date": ymd(YEAR, month, clamp_day(5 + n % 20, month)),
            "amount": rp(rng, 100_000, 400_000, 10_000),
            "apply_to": apply_to,
        })
    # GET /finance/supplier-advances only lists OUTSTANDING advances (see
    # `finance.py`'s own note on this endpoint), so a fully-applied one from a
    # previous run disappears from it — this must not be read as "not made
    # yet" and recreated. `have_refs` therefore only tells us what is still
    # open; anything not in it that we still want to apply against is assumed
    # already made (the create call's own reference conflict, if any, is
    # swallowed below rather than allowed to abort the rest of the plan).
    have = {a.get("reference"): a for a in rows(cloud.get("/api/v1/finance/supplier-advances")) if a.get("reference")}
    made = applied = refused = 0
    for item in plan:
        try:
            po = pos.get(item["po_number"])
            if po is None:
                continue
            adv = have.get(item["reference"])
            if adv is None:
                adv = cloud.post("/api/v1/finance/supplier-advances", {
                    "purchase_order_id": po["purchase_order_id"], "unit_id": HO_UNIT,
                    "advance_date": item["date"], "amount_minor": item["amount"],
                    "account_key": BANK_KEY, "account_qualifier": BANK_Q,
                    "reference": item["reference"], "note": f"Uang muka {item['po_number']} (volume seed)"})
                aid = adv.get("advance_id") or adv.get("id")
                if (adv.get("status") or "DRAFT") == "DRAFT":
                    cloud.post(f"/api/v1/finance/supplier-advances/{aid}/post", {})
                made += 1
            else:
                aid = adv.get("advance_id") or adv.get("id")
            target = bills_by_number.get(item["apply_to"] or "")
            if target and (target.get("outstanding_minor") or 0) >= item["amount"]:
                cloud.post(f"/api/v1/finance/supplier-advances/{aid}/apply", {
                    "invoice_id": target["invoice_id"], "amount_minor": item["amount"],
                    "posting_date": item["date"]})
                applied += 1
        except (SystemExit, Exception) as error:  # noqa: BLE001 — one bad advance must not abort the plan
            refused += 1
    say(f"+ supplier advances: {made} issued (of {len(plan)} planned), {applied} applied to bills, "
        f"{refused} refused/already settled")


