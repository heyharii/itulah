import { node } from "@/lib/api"
import type {
  CreateSupplierItemRequest,
  SourcedItem,
  Supplier,
  SupplierItem,
  SupplierStatus,
} from "@itulah/contract"

/// Sourcing is one question — "who sells this, and for how much" — so the
/// server answers it in one request. `GET /api/v1/supplier-items` matches an
/// item's name or code, or the supplier's name, and returns the supplier
/// attached to each row. The browser never stitches suppliers to items itself:
/// that would put the definition of "matches" in a place nobody can see, and
/// would cost one request per supplier.
export interface SourcingScope {
  /// Free text, matched server-side against item name, item code and supplier
  /// name.
  readonly q?: string
  readonly supplierId?: string
  readonly status?: SupplierStatus
  readonly limit?: number
}

function scopeToQuery(scope: SourcingScope): string {
  const params = new URLSearchParams()
  if (scope.q !== undefined && scope.q.trim() !== "") params.set("q", scope.q.trim())
  if (scope.status !== undefined) params.set("status", scope.status)
  if (scope.supplierId !== undefined) params.set("supplier_id", scope.supplierId)
  if (scope.limit !== undefined) params.set("limit", String(scope.limit))
  const query = params.toString()
  return query === "" ? "" : `?${query}`
}

export function searchSourcedItems(
  scope: SourcingScope = {},
  signal?: AbortSignal,
): Promise<SourcedItem[]> {
  return node.get<SourcedItem[]>(`/api/v1/supplier-items${scopeToQuery(scope)}`, { signal })
}

export function listSuppliers(
  status?: SupplierStatus,
  signal?: AbortSignal,
): Promise<Supplier[]> {
  const query = status === undefined ? "" : `?status=${status}`
  return node.get<Supplier[]>(`/api/v1/suppliers${query}`, { signal })
}

/// Add a candidate to a supplier's catalogue.
///
/// The key is generated by the caller and held across retries — the server
/// stores it with a digest of the request and replays its first answer, so a
/// double-submitted form adds one item, not two.
export function createSupplierItem(
  supplierId: string,
  request: CreateSupplierItemRequest,
  idempotencyKey: string,
  signal?: AbortSignal,
): Promise<SupplierItem> {
  return node.post<SupplierItem>(`/api/v1/suppliers/${supplierId}/items`, request, {
    signal,
    headers: { "idempotency-key": idempotencyKey },
  })
}

/// The two facets the rows carry that the server does not filter on.
///
/// Division and tags live on the item (`division_code`, `tags`) and the
/// backend's sourcing query does not accept them, so they are faceted in the
/// browser off the rows already fetched. That is honest as long as the row set
/// is the whole answer — which is why the limit is raised rather than paged.
export function divisionsOf(rows: readonly SourcedItem[]): string[] {
  const seen = new Set<string>()
  for (const row of rows) {
    if (row.item.division_code !== null) seen.add(row.item.division_code)
  }
  return [...seen].sort((a, b) => a.localeCompare(b))
}

export function tagsOf(rows: readonly SourcedItem[]): string[] {
  const seen = new Set<string>()
  for (const row of rows) {
    for (const tag of row.item.tags) seen.add(tag)
  }
  return [...seen].sort((a, b) => a.localeCompare(b))
}
