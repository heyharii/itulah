/* Photography and article numbers come from the image set in
 * ~/Documents/retail/images_selected. The articles.csv beside it does NOT
 * describe these photos — it is fabricated (0146721 is labelled 'Shorts'
 * there but is a metal hair cuff), so none of its names, types, colours or
 * descriptions are used here.
 *
 * Real: the photograph, the article number, and the colourway grouping
 *   (an H&M article id is <7-digit style><3-digit colour>, so the variants
 *   of one style really are the same product in another colour).
 * Named by hand: the styles marked `verified`, read off the photo.
 * Synthesized: price, MOQ, lead time, supplier, status.
 */

export interface Colorway {
  id: string
  image: string
}

export interface Supplier {
  id: string
  name: string
  /**
   * The mill or workshop inside the supplier.
   *
   * Optional because Internal does not send it: `master_suppliers` has no
   * `primary_division` column, verified against the live schema. The mapper
   * used to default it to the literal string "Supplier", which rendered under
   * every supplier name and read as data. An absent field is honest; a
   * placeholder that looks like a value invites filtering on nothing.
   */
  division?: string
  country: string
  hue: string
}

export type ProductStatus = "active" | "sampling" | "paused"

export interface Product {
  id: string
  name: string
  sku: string
  /** A real variant SKU when Internal returns one; family/base codes are not PO SKUs. */
  variantSku?: string
  /** Relational sourcing-item identity, when this row came from /v1/sourcing. */
  sourcingItemId?: string
  category: string
  /** Canonical master_divisions id used by procurement writes. */
  divisionId?: string
  /** True when the name was read off the photograph rather than guessed. */
  verified: boolean
  price: number
  moq: number
  leadTime: number
  supplierId: string
  tags: string[]
  status: ProductStatus
  updated: number
  colorways: Colorway[]
  /** Backend money currency; legacy seeded catalogue defaults to USD. */
  currency?: string
}

